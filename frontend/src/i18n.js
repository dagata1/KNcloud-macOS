export function trMsg(msg) {
  if (msg === null || msg === undefined) return msg;
  let s = String(msg);
  if (current !== 'en' || !/[\u3000-\u9fff\uff00-\uffef]/.test(s)) return s;
  if (Object.prototype.hasOwnProperty.call(en, s)) return en[s];
  for (const [re, rep] of BACKEND) s = s.replace(re, rep);
  return s.replace(/\s+\)/g, ')').replace(/ {2,}/g, ' ').trim();
}

