// 系统语言：zh* → zh-CN，其余 → en
export function detectSystemLang() {
  try {
    const l = (navigator.languages && navigator.languages[0]) || navigator.language || '';
    return /^zh/i.test(l) ? 'zh-CN' : 'en';
  } catch (_) {
    return 'zh-CN';
  }
}

export function normalizeLangPref(p) {
  return p === 'zh-CN' || p === 'en' ? p : 'system';
}

export function resolveLang(pref) {
  const p = normalizeLangPref(pref);
  return p === 'system' ? detectSystemLang() : p;
}

const LS_KEY = 'kncloud.language';
export function loadCachedLangPref() {
  try { return normalizeLangPref(localStorage.getItem(LS_KEY)); } catch (_) { return 'system'; }
}
export function cacheLangPref(p) {
  try { localStorage.setItem(LS_KEY, normalizeLangPref(p)); } catch (_) { /* 忽略 */ }
}

